/**
 * Set the active language and update all translated elements
 */
function setLanguage(lang) {
    if (!translations[lang]) return;

    localStorage.setItem('charwa_lang', lang);
    document.documentElement.lang = lang;

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    // Update title attributes
    document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-title');
        if (translations[lang][key]) {
            el.title = translations[lang][key];
        }
    });

    // Update active language button
    document.querySelectorAll('.lang-selector button').forEach(function(btn) {
        btn.classList.toggle('active', btn.textContent.trim() === lang.toUpperCase());
    });
}

/**
 * Get a translation by key for the current language
 */
function t(key) {
    var lang = localStorage.getItem('charwa_lang') || 'de';
    return (translations[lang] && translations[lang][key]) || key;
}

// Initialize language on page load
(function() {
    var saved = localStorage.getItem('charwa_lang') || 'de';
    setLanguage(saved);
})();
